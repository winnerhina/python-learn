# 实际体验
s = "hello-python-hello-word"
# find(子串)---查找字符串里面的子串，返回子串第一次出现的位置，若没找到，返回-1
index = s.find("-")
print(index)
# count()---统计子串在字符串中出现的次数  
c = s.count("o")
print(c)


# ----------------------------------------------------------------------------------------
# upper()---将字符串里面的字母全部转换为大写---无参数
da = s.upper()
print(da)
# lower()---将字符串里面的字母全部转换为小写---无参数
ss = "HELLO-PYTHON-HELLO-WORD"
da = ss.lower()
print(da)
# split(分割标志字符)---将字符串按指定分隔符分割成列表
qie = s.split('-')
qie1 = s.split('o')
print(qie)
print(qie1)
# strip()---删除字符串两端首个白字符或指定字符---默认去除空格
qu = s.strip('h')
print(qu)
# replace('a','b')---将字符串内指定的子串a替换为指定的子串b
hu = s.replace("o","6")
hu1 = s.replace("he","666")
print(hu)
print(hu1)
# 注意：不论看起来怎么改，他会返回改好的字符，并不会修改原字符串（重点）

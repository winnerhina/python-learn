# 练习1：输入一个字符串，判断是否是回文（两边对称）
# 方法一：
# 思路：回文=正着读和倒着读一样。用切片[::-1]反转整个字符串，和原串比较
s = input("请输入一个字符串：")
if s == s[::-1]:
    print(f"“{s}”是回文")
else:
    print(f"“{s}”不是回文")

# 方法二：
# 思路：左右双指针，逐对比较
left = 0
right = len(s) - 1
is_hui = True
while left < right:
    if s[left] != s[right]:   # 有一对不相等就不是回文
        is_hui = False
        break
    left += 1
    right -= 1
print(f"“{s}”{'是' if is_hui else '不是'}回文")

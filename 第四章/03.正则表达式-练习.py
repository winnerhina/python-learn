import re

# ============ 练习1：提取手机号 ============
# 需求：使用 re.findall 从下面的句子中提取所有手机号
# 提示：手机号规则为 1 开头、第二位是 3-9、共 11 位，即 1[3-9]\d{9}
# 注意：座机号 021-12345678 不是手机号，不应被提取
s1 = "我的手机号是13812345678，另一个是15987654321，座机电话是021-12345678，有问题请联系我。"
# 期望输出：['13812345678', '15987654321']

# TODO: 写出你的代码
result1 = re.findall(r"1[3-9]\d{9}", s1)
print(result1)


# ============ 练习2：提取邮箱 ============
# 需求：使用 re.findall 从下面的文本中提取所有邮箱地址
# 提示：邮箱一般由 用户名@域名.后缀 组成，例如 zhangsan@qq.com，
#       可尝试用 \w+@\w+\.\w+ 组合出匹配模式
s2 = "联系人 zhangsan@qq.com 或 lisi@163.com，客服邮箱 12345@qq.com。"
# 期望输出：['zhangsan@qq.com', 'lisi@163.com', '12345@qq.com']

# TODO: 写出你的代码
result2 = re.findall(r"\w+@\w+\.\w+", s2)
print(result2)
